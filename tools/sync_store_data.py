#!/usr/bin/env python3
"""Refresh site/src/data/apps/<slug>.json from the App Store plus apps.manual.json.

Usage:  python3 tools/sync_store_data.py
Reads   site/src/data/apps.manual.json   (hand-maintained facts; edit this one)
Writes  site/src/data/apps/<slug>.json   (generated; do not edit by hand)

App Store data comes from the public iTunes Lookup API (US storefront).
Google Play has no public API, so Play facts live in apps.manual.json.
"""
import html, json, os, re, sys, urllib.request
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "site", "src", "data")
DEVELOPER_ID = 1614396757

# Words in the App Store description that tell us which system surfaces an app uses.
SURFACES = {
    "widgets": r"\bwidgets?\b",
    "liveActivities": r"Live Activit",
    "dynamicIsland": r"Dynamic Island",
    "controlCenter": r"Control Cent(er|re)",
    "standBy": r"StandBy",
    "complications": r"complications?",
    "siri": r"\bSiri\b",
    "shortcuts": r"\bShortcuts\b",
    "spotlight": r"\bSpotlight\b",
    "iCloud": r"\biCloud\b",
}


def lookup():
    url = f"https://itunes.apple.com/lookup?id={DEVELOPER_ID}&entity=software&limit=200&country=us"
    with urllib.request.urlopen(url, timeout=30) as r:
        res = json.load(r)["results"]
    return {a["trackId"]: a for a in res if a.get("wrapperType") == "software"}


UA = {"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36"}


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as r:
        return r.read()


def play_listing(package):
    """Best-effort read of the public Play listing: description and screenshot URLs.
    Google Play has no public API, so this parses the page and may need updating if Google changes it."""
    page = fetch(f"https://play.google.com/store/apps/details?id={package}&hl=en&gl=US").decode("utf-8", "ignore")
    m = re.search(r'<div[^>]*data-g-id="description"[^>]*>(.*?)</div>', page, re.S)
    desc = ""
    if m:
        desc = html.unescape(re.sub(r"<[^>]+>", "", re.sub(r"<br\s*/?>", "\n", m.group(1)))).strip()
    shots = []
    for src in re.findall(r'<img src="(https://play-lh\.googleusercontent\.com/[^"=]+)=[^"]*"[^>]*alt="Screenshot image"', page):
        if src not in shots:
            shots.append(src)
    return desc, shots


def download_screenshots(slug, urls, kind):
    """Save store screenshots next to the site so pages never hotlink Apple's or Google's CDN."""
    out = os.path.join(ROOT, "assets", "apps", slug)
    os.makedirs(out, exist_ok=True)
    saved = []
    for i, u in enumerate(urls[:8], 1):
        if "mzstatic.com" in u:
            u = u.rsplit("/", 1)[0] + "/600x0w.webp"   # Apple's CDN resizes and converts on request
        else:
            u = u + "=w600-rw"                          # Google's CDN: 600px wide, WebP
        name = f"{kind}-{i:02d}.webp"
        path = os.path.join(out, name)
        if not os.path.exists(path):
            with open(path, "wb") as f:
                f.write(fetch(u))
        saved.append(f"/assets/apps/{slug}/{name}")
    return saved


def platforms(a):
    dev = a.get("supportedDevices", [])
    has = lambda p: any(d.startswith(p) for d in dev)
    return {
        "iphone": has("iPhone"),
        "ipad": has("iPad"),
        # MacDesktop in supportedDevices = a native Mac build. Otherwise the iPad app may run on
        # Apple silicon Macs ("Designed for iPad"); App Store pages confirm it per app.
        "mac": "native" if has("MacDesktop") else "ipad-app",
        "watch": has("Watch"),
        "vision": "ipad-app",
    }


def write_accent_css(manual):
    """One rule per app so a page only has to set data-app="<slug>" on <html>."""
    b = manual["brand"]
    lines = ["/* Generated by tools/sync_store_data.py from apps.manual.json. Do not edit. */",
             f':root {{ --app-accent: {b["accent"]}; --app-accent-ink: {b["accentInk"]}; --app-on-accent: {b["accentOn"]}; }}',
             f'@media (prefers-color-scheme: dark) {{ :root {{ --app-accent-ink: {b["accentInkDark"]}; }} }}']
    for a in manual["apps"]:
        lines.append(f'[data-app="{a["slug"]}"] {{ --app-accent: {a["accent"]}; --app-accent-ink: {a["accentInk"]}; --app-on-accent: {a["accentOn"]}; }}')
        lines.append(f'@media (prefers-color-scheme: dark) {{ [data-app="{a["slug"]}"] {{ --app-accent-ink: {a["accentInkDark"]}; }} }}')
    path = os.path.join(ROOT, "site", "src", "styles", "app-accents.css")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(lines) + "\n")


def main():
    manual = json.load(open(os.path.join(DATA, "apps.manual.json")))["apps"]
    store = lookup()
    known = {m["appStoreId"] for m in manual if m["appStoreId"]}
    missing = [f'{a["trackId"]} {a["trackName"]}' for a in store.values() if a["trackId"] not in known]
    if missing:
        print("App Store apps not in apps.manual.json:", *missing, sep="\n  ")
    out_dir = os.path.join(DATA, "apps")
    os.makedirs(out_dir, exist_ok=True)
    for m in manual:
        a = store.get(m["appStoreId"]) if m["appStoreId"] else None
        if m["appStoreId"] and not a:
            print(f'WARNING {m["slug"]}: App Store id {m["appStoreId"]} not returned by the API')
        desc = a.get("description", "") if a else ""
        # orlproducts.pages.dev no longer resolves: point those links at the live site
        desc = re.sub(r"https?://orlproducts\.pages\.dev/(privacy|terms)(\.html)?", r"https://orlproducts.com/\1.html", desc)
        desc = re.sub(r"https?://orlproducts\.pages\.dev/?", "https://orlproducts.com/", desc)
        for find, repl in m.get("textFixes", []):
            if find not in desc and desc:
                print(f'WARNING {m["slug"]}: text fix not applied, source changed: {find[:50]!r}')
            desc = desc.replace(find, repl)
        play_shots = []
        if not a and m.get("playPackage"):
            try:
                desc, play_shots = play_listing(m["playPackage"])
            except Exception as e:
                print(f'WARNING {m["slug"]}: could not read the Play listing ({e})')
        shots = {}
        if m.get("generatePage"):
            if a:
                shots["iphone"] = download_screenshots(m["slug"], a.get("screenshotUrls", []), "iphone")
                shots["ipad"] = download_screenshots(m["slug"], a.get("ipadScreenshotUrls", []), "ipad")
            elif play_shots:
                shots["android"] = download_screenshots(m["slug"], play_shots, "android")
        rec = {
            "_generated": "by tools/sync_store_data.py — edit apps.manual.json instead",
            "slug": m["slug"],
            "name": (a["trackName"] if a else m.get("name")),
            "subtitle": m.get("subtitle"),
            "brand": m.get("brand"),      # short name people know the app by (PaddlePilot)
            "tagline": m.get("tagline"),  # what it is, from the store name (Kayak, Canoe & SUP)
            "group": m["group"],
            "priority": m["priority"],
            "accent": {"base": m.get("accent"), "ink": m.get("accentInk"), "inkDark": m.get("accentInkDark"), "on": m.get("accentOn")},
            "category": a["primaryGenreName"] if a else m.get("category"),
            "appStore": None if not a else {
                "id": a["trackId"],
                "url": f'https://apps.apple.com/app/id{a["trackId"]}',
                "bundleId": a["bundleId"],
                "version": a["version"],
                "released": a["releaseDate"][:10],
                "updated": a["currentVersionReleaseDate"][:10],
                "minimumOs": a["minimumOsVersion"],
                "languages": [l.lower() for l in a.get("languageCodesISO2A", [])],
                "price": a["formattedPrice"],
                "rating": {"value": round(a["averageUserRating"], 2), "count": a["userRatingCount"]} if a.get("userRatingCount") else None,
                "contentRating": a.get("trackContentRating"),
                "icon": a["artworkUrl512"],
                "developerWebsite": a.get("sellerUrl"),
                "screenshots": {"iphone": len(a.get("screenshotUrls", [])), "ipad": len(a.get("ipadScreenshotUrls", []))},
            },
            "iosStatus": "live" if a else m.get("iosStatus"),
            "googlePlay": None if not m.get("playPackage") else {
                "package": m["playPackage"],
                "url": f'https://play.google.com/store/apps/details?id={m["playPackage"]}',
            },
            "androidStatus": "live" if m.get("playPackage") else m.get("androidStatus"),
            "platforms": {**(platforms(a) if a else {}), **({"vision": "native"} if m.get("visionNative") else {}), "android": bool(m.get("playPackage")), "wearOs": m.get("wearOs", False)},
            # CarPlay is never inferred from text (Volume Booster mentions it only as an audio output):
            # it comes from apps.manual.json, set for apps whose store text describes a CarPlay feature.
            "surfaces": {**{k: bool(re.search(p, desc, re.I)) for k, p in SURFACES.items()}, "carPlay": bool(m.get("carPlay"))},
            "web": m["web"],
            "generatePage": bool(m.get("generatePage")),
            "generateSupport": bool(m.get("generateSupport")),
            "contentLang": m.get("contentLang", "en"),
            "metaDescription": m.get("metaDescription"),
            "description": desc,
            "screenshots": shots,
            "issues": [],
        }
        site = (rec["appStore"] or {}).get("developerWebsite") or ""
        if "pages.dev" in site:
            rec["issues"].append(f"App Store Developer Website points to {site}, which does not resolve.")
        if not m["web"]["privacy"]:
            rec["issues"].append("No app-specific privacy policy page on orlproducts.com.")
        if not m["web"]["landing"]:
            rec["issues"].append("No landing page on orlproducts.com.")
        with open(os.path.join(out_dir, f'{m["slug"]}.json'), "w") as f:
            json.dump(rec, f, ensure_ascii=False, indent=2)
            f.write("\n")
    write_accent_css(json.load(open(os.path.join(DATA, "apps.manual.json"))))
    print(f"Wrote {len(manual)} files to {os.path.relpath(out_dir, ROOT)} on {date.today()}")


if __name__ == "__main__":
    sys.exit(main())
